class DataTypeDemo {
    public static void main(String[] args) {
        int age = 21;
        float percent = 85.5f;
        double sal = 50000.75;
        char grade = 'A';
        boolean isPass = true;
        System.out.println("Int Value: " + age);
        System.out.println("Float Value: " + percentage);
        System.out.println("Double Value: " + salary);
        System.out.println("Chara Value: " + grade);
        System.out.println("Bool Value: " + isPassed);
    }
}